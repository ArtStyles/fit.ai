export function normalizeLanguage(value: string | null | undefined): AppLanguage {
  return value === 'en' ? 'en' : 'es'
}

export function translate(
  language: AppLanguage,
  source: string,
  values?: TranslationValues,
): string {
  let result = language === 'en' ? ENGLISH[source] ?? source : source

  if (values) {
    for (const [key, value] of Object.entries(values)) {
      result = result.replaceAll(`{${key}}`, String(value))
    }
  }

  return result
}

export function createTranslator(language: AppLanguage) {
  return (source: string, values?: TranslationValues) => translate(language, source, values)
}

export function dateLocale(language: AppLanguage): string {
  return language === 'en' ? 'en-US' : 'es-ES'
}

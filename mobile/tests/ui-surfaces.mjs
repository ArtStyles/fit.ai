import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'

const browser = await chromium.launch({ headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await context.addInitScript(() => Object.defineProperty(navigator, 'onLine', { get: () => false }))
  await context.route('**/*', route => route.request().url().startsWith('http://127.0.0.1:4178/') ? route.continue() : route.abort())
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:4178')
  await page.getByLabel('Tu nombre').fill('María')
  await page.getByLabel('Edad', { exact: true }).fill('32')
  await page.getByLabel('Presento dolor torácico', { exact: false }).check()
  await page.getByLabel('He revisado mis respuestas', { exact: false }).check()
  await page.getByRole('button', { name: 'Crear mi espacio' }).click()
  await page.getByRole('button', { name: 'Crear mi primera rutina' }).click()
  await page.getByRole('alert').filter({ hasText: 'profesional' }).waitFor()
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click()
  await page.getByRole('button', { name: 'Editar perfil y preparación' }).click()
  assert.equal(await page.getByLabel('Presento dolor torácico', { exact: false }).isChecked(), true)
  await page.getByLabel('Presento dolor torácico', { exact: false }).uncheck()
  await page.getByLabel('He revisado mis respuestas', { exact: false }).check()
  await page.getByRole('button', { name: 'Guardar perfil' }).click()
  await page.getByRole('button', { name: 'Crear mi primera rutina' }).waitFor()
  for (const width of [360, 390, 768]) {
    await page.setViewportSize({ width, height: 844 })
    await page.screenshot({ path: `mobile/tests/home-${width}.png`, fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
  await page.getByRole('button', { name: 'Ejercicios', exact: true }).click()
  await page.getByLabel('Buscar ejercicio').fill('sentadilla')
  const card = page.locator('.catalog-card').first()
  await card.click()
  await page.getByRole('dialog').waitFor()
  await page.locator('.exercise-dialog img').evaluate(img => img.decode())
  await page.screenshot({ path: 'mobile/tests/exercise-768.png', fullPage: true })
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  await page.getByLabel('Buscar ejercicio').fill('')
  for (const width of [360, 390, 768]) {
    await page.setViewportSize({ width, height: 844 })
    await page.screenshot({ path: `mobile/tests/catalog-${width}.png`, fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
  await page.getByRole('button', { name: 'Historial', exact: true }).click()
  await page.getByLabel('Peso (kg)', { exact: true }).fill('73.5')
  await page.getByLabel('Cintura (cm)', { exact: true }).fill('82')
  await page.getByRole('button', { name: 'Guardar medida' }).click()
  await page.getByText('Medida guardada', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: 'Historial', exact: true }).click()
  await page.getByText('73.5 kg · 82 cm', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Entrenadores', exact: true }).click()
  await page.getByText('Tu próximo paso, acompañado', { exact: true }).waitFor()
  await page.screenshot({ path: 'mobile/tests/trainers-768.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: readiness blocking and persistence, corrections, local measurements reload, catalog detail/keyboard, offline trainers, responsive 360/390/768')
} finally { await browser.close() }
